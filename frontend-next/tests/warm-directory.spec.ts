const cards = (page: import('@playwright/test').Page) => page.getByRole('button', { name: /^查看.+详情$/ })

test('目录默认展示30家，筛选改变结果并重置分页', async ({ page }) => {
  const integrity = watchBrowserIntegrity(page)
  await page.goto('/washjoy/', { waitUntil: 'domcontentloaded' })
  const search = page.getByRole('searchbox', { name: '搜索门店' })
  await expect(search).toBeVisible()
  await expect(cards(page)).toHaveCount(30)
  await expect(page.getByRole('button', { name: '查看地图' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '继续查找可达门店', exact: true }).click()
  await page.getByRole('button', { name: '再看 4 家' }).click()
  await expect(cards(page)).toHaveCount(34)
  await expect(page.getByRole('button', { name: /再看.*家/ })).toHaveCount(0)

  await search.fill('静安私汤')
  await expect(cards(page)).toHaveCount(1)
  await expect(cards(page)).toHaveAccessibleName('查看静安私汤详情')
  await page.getByRole('button', { name: '清除搜索' }).click()
  await expect(cards(page)).toHaveCount(30)

  const categories = page.getByRole('group', { name: '门店类型' })
  await categories.getByRole('button', { name: '私汤', exact: true }).click()
  await expect(cards(page)).toHaveCount(1)
  await expect(categories.getByRole('button', { name: '私汤', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await categories.getByRole('button', { name: '全部', exact: true }).click()
  await page.getByRole('button', { name: '推荐', exact: true }).click()
  await expect(page.getByRole('button', { name: '推荐', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(cards(page)).toHaveCount(17)
  await expect(page.getByRole('button', { name: '查看静安私汤详情' })).toHaveCount(0)
  await page.getByRole('button', { name: '推荐', exact: true }).click()
  await expect(cards(page)).toHaveCount(30)
  await integrity.expectClean()
})

test('地图切换保留搜索、类型和推荐，返回列表后可清除空结果', async ({ page }) => {
  await page.goto('/washjoy/', { waitUntil: 'domcontentloaded' })
  const search = page.getByRole('searchbox', { name: '搜索门店' })
  await search.fill('测试洗浴门店')
  await page.getByRole('group', { name: '门店类型' }).getByRole('button', { name: '洗浴中心', exact: true }).click()
  await page.getByRole('button', { name: '推荐', exact: true }).click()
  const before = await cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))
  expect(before.length).toBeGreaterThan(0)
  await page.getByRole('button', { name: '查看地图' }).click()
  await expect(page.getByRole('application', { name: '地图', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看列表' })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('#washjoy-map').evaluate(element => element.setAttribute('data-retained-check', 'yes'))
  await page.getByRole('button', { name: '查看列表' }).click()
  await expect(page.getByRole('application', { name: '地图', exact: true })).toHaveCount(0)
  await expect(page.locator('#washjoy-map')).toHaveAttribute('data-retained-check', 'yes')
  await expect(page.locator('#washjoy-map')).toBeHidden()
  await page.getByRole('button', { name: '查看地图', exact: true }).click()
  await expect(page.locator('#washjoy-map')).toHaveAttribute('data-retained-check', 'yes')
  await expect(page.locator('#washjoy-map')).toBeVisible()
  await page.getByRole('button', { name: '查看列表', exact: true }).click()
  await expect(search).toHaveValue('测试洗浴门店')
  await expect(page.getByRole('button', { name: '推荐', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => cards(page).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')))).toEqual(before)
  await search.fill('完全没有匹配的门店关键词')
  await expect(cards(page)).toHaveCount(0)
  await expect(page.getByText('没有匹配的门店', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: '清除筛选', exact: true }).click()
  await expect(search).toHaveValue('')
  await expect(cards(page)).toHaveCount(30)
})

