test('筛选面板保留范围、可达时间及三种出行方式', async ({ page }) => {
  await page.goto('/washjoy/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: '可达时间筛选' }).click()
  const filters = page.getByRole('dialog', { name: '筛选附近门店' })
  const radius = filters.getByRole('combobox', { name: '搜索范围' })
  await radius.selectOption('1')
  await expect(radius).toHaveValue('1')
  const duration = filters.getByRole('combobox', { name: '可达时间' })
  await expect(duration.locator('option')).toHaveText(['无限制', '15 分钟', '30 分钟', '45 分钟', '60 分钟'])
  await duration.selectOption('0')
  const travel = filters.getByRole('group', { name: '出行方式' })
  await expect(travel.getByRole('button')).toHaveText(['公交地铁', '骑行', '驾车'])
  await travel.getByRole('button', { name: '驾车', exact: true }).click()
  await expect(travel.getByRole('button', { name: '驾车', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await filters.getByRole('button', { name: '完成筛选' }).click()
  await expect(filters).toBeHidden()
  await expect(cards(page)).toHaveCount(30)
  await page.getByRole('button', { name: '查看地图' }).click()
  await page.getByRole('button', { name: '可达时间筛选' }).click()
  await expect(duration).toHaveValue('0')
  await expect(radius).toHaveValue('1')
  await expect(travel.getByRole('button', { name: '驾车', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await filters.getByRole('button', { name: '关闭筛选' }).click()
  await expect(filters).toBeHidden()
})

test('深浅色、减少动态及窄屏保持语义控件和触点可用', async ({ page }) => {
  const integrity = watchBrowserIntegrity(page)
  await page.goto('/washjoy/', { waitUntil: 'domcontentloaded' })
  await expect(cards(page)).toHaveCount(30)
  await expectNoHorizontalOverflow(page)
  await expectTouchTarget(page.getByRole('button', { name: '推荐', exact: true }))
  await expectTouchTarget(page.getByRole('button', { name: '可达时间筛选' }))
  await expectTouchTarget(page.getByRole('button', { name: '查看地图' }))
  await expect.poll(() => page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches)).toBe(true)
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running' && animation.effect?.getTiming().iterations === Infinity).length)).toBe(0)
  const theme = await page.evaluate(() => ({ dark: matchMedia('(prefers-color-scheme: dark)').matches, scheme: getComputedStyle(document.documentElement).colorScheme }))
  expect(theme.scheme).toContain(theme.dark ? 'dark' : 'light')
  await integrity.expectClean()
})


