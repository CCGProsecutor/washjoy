test('长门店名保持自然换行，标题触点不压住说明', async ({ page }) => {
  const name = '松间汤泉养生休憩会馆'.repeat(8)
  await page.route('**/washjoy/api/public-data?**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ pois: [{ id: 'long-title', name, photos: [], location: '118.7969,32.0603', address: '南京市测试地址' }] }) }))
  await page.goto('/washjoy/')
  const card = page.getByRole('article', { name, exact: true })
  await expect(card).toBeVisible()
  const title = card.getByRole('button', { name, exact: true })
  await expectTouchTarget(title)
  const titleBox = await title.boundingBox()
  const descriptionBox = await card.locator('.wj-venue-caption p').boundingBox()
  expect(descriptionBox!.y).toBeGreaterThanOrEqual(titleBox!.y + titleBox!.height - 1)
  await expectNoHorizontalOverflow(page)
})
