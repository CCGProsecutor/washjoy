CREATE TABLE IF NOT EXISTS users (
    phone TEXT PRIMARY KEY,
    pass TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('user', 'admin')),
    profile JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    phone TEXT NOT NULL REFERENCES users(phone) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS reg_limit (
    ip TEXT PRIMARY KEY,
    attempted_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS login_fail (
    key TEXT PRIMARY KEY,
    attempts INTEGER NOT NULL CHECK (attempts >= 0),
    locked_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS store_overrides (
    id TEXT PRIMARY KEY,
    city TEXT NOT NULL,
    category TEXT NOT NULL,
    data JSONB NOT NULL,
    manual BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL,
    by_user TEXT NOT NULL REFERENCES users(phone)
);

CREATE INDEX IF NOT EXISTS store_overrides_city_idx ON store_overrides(city);
CREATE INDEX IF NOT EXISTS store_overrides_visible_idx ON store_overrides(city, deleted);

CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id TEXT NOT NULL,
    place_name TEXT NOT NULL,
    city TEXT NOT NULL,
    phone TEXT NOT NULL REFERENCES users(phone) ON DELETE RESTRICT,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS reviews_place_idx ON reviews(place_id, id DESC);
CREATE INDEX IF NOT EXISTS reviews_phone_idx ON reviews(phone, id DESC);
